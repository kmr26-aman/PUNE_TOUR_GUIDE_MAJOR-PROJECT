export const getPlacePhotoList = (place) => {
  if (!place) return ["https://images.unsplash.com/photo-1589308078059-be1415eab4c3?auto=format&fit=crop&w=800&q=80"];

  if (place.image && place.image.startsWith("http")) {
    return [place.image];
  }
  if (place.imageUrl && place.imageUrl.startsWith("http")) {
    return [place.imageUrl];
  }

  const nameKey = (place.name || "").toLowerCase().trim();
  for (const [key, photos] of Object.entries(PLACE_PHOTO_MAP)) {
    if (nameKey.includes(key) || key.includes(nameKey)) {
      return photos;
    }
  }

  // Category based defaults
  const category = (place.category || "").toLowerCase();
  if (category.includes("heritage")) {
    return [
      "https://images.unsplash.com/photo-1589308078059-be1415eab4c3?auto=format&fit=crop&w=800&q=80",
      "https://images.unsplash.com/photo-1609828913647-7576722d36d2?auto=format&fit=crop&w=800&q=80"
    ];
  }
  if (category.includes("temple")) {
    return [
      "https://images.unsplash.com/photo-1662446736466-9b57d079942a?auto=format&fit=crop&w=800&q=80",
      "https://images.unsplash.com/photo-1606216794074-735e91aa2c92?auto=format&fit=crop&w=800&q=80"
    ];
  }
  if (category.includes("nature")) {
    return [
      "https://images.unsplash.com/photo-1626014903708-ecb661d9a26a?auto=format&fit=crop&w=800&q=80",
      "https://images.unsplash.com/photo-1507525428034-b723cf961d3e?auto=format&fit=crop&w=800&q=80"
    ];
  }
  if (category.includes("food")) {
    return [
      "https://images.unsplash.com/photo-1567157577867-05ccb1388e66?auto=format&fit=crop&w=800&q=80",
      "https://images.unsplash.com/photo-1517248135467-4c7edcad34c4?auto=format&fit=crop&w=800&q=80"
    ];
  }

  return [
    "https://images.unsplash.com/photo-1589308078059-be1415eab4c3?auto=format&fit=crop&w=800&q=80",
    "https://images.unsplash.com/photo-1570168007204-dfb528c6958f?auto=format&fit=crop&w=800&q=80"
  ];
};

export const getSinglePlacePhoto = (place) => {
  const photos = getPlacePhotoList(place);
  return photos[0];
};
